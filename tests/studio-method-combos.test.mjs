import assert from 'node:assert/strict';
import {METHOD_COMBOS,checkMethodSource,mapMethodToStates} from '../assets/js/authoring/method-combo-catalog.js';
assert.equal(Object.keys(METHOD_COMBOS).length,29);
assert.ok(Object.values(METHOD_COMBOS).every(c=>c.steps.some(s=>s.mode==='individual')&&c.steps.some(s=>s.mode==='pair'||s.mode==='group')));
assert.ok(Object.values(METHOD_COMBOS).filter(c=>c.group==='Listening').length>=5);
assert.ok(Object.values(METHOD_COMBOS).filter(c=>c.group==='Reading').length>=4);
for(const [id,combo] of Object.entries(METHOD_COMBOS)){
 assert.ok(combo.required.length>=1,id+' missing required schema');
 assert.ok(combo.steps.length>=4,id+' needs learning progression');
 assert.equal(new Set(combo.steps.map(x=>x.id)).size,combo.steps.length,id+' duplicate state');
 assert.ok(combo.steps.every(x=>x.instruction&&x.label&&x.slot),id+' missing learner instruction');
 assert.equal(mapMethodToStates(id,{}).ok,false,'Must reject missing original material');
}
const question=i=>({id:'q'+i,text:'Original question '+i,answers:['Verified answer '+i],sourceRef:'Original book p.141 q'+i,evidenceQuote:'Verified supporting sentence '+i,why:'Verified evidence supports original question '+i});
const source={audioSrc:'/audio/original.mp3',expectedQuestionCount:5,questions:[1,2,3,4,5].map(question),gistQuestion:'What is the main idea?',groupTask:'Share the details with classmates.'};
const mapped=mapMethodToStates('tbl-listening',source);
assert.equal(mapped.ok,true);
assert.equal(mapped.states.length,6);
assert.equal(mapped.originalQuestionCount,5);
assert.deepEqual(mapped.states.find(x=>x.id==='complete').material,source.questions.map(q=>({id:q.id,text:q.text})));
assert.ok(!JSON.stringify(mapped.states).includes('Verified answer 1'), 'No actual answer value in learner step data');
assert.ok(!JSON.stringify(mapped.states).includes('Verified supporting sentence'), 'No Evidence leak in learner step data');
assert.equal(mapped.states.find(x=>x.id==='complete').answerPolicy,'hidden');
assert.ok(mapped.states.every(s=>s.requiresServerIssuedRoleGrants===true));
assert.ok(mapped.states.every(x=>x.id==='complete'||x.answerPolicy==='hidden'));
assert.equal(mapped.status,'needs-teacher-review');
const shortened={...source,questions:source.questions.slice(0,3)};
assert.ok(checkMethodSource('tbl-listening',shortened).some(s=>s.includes('mismatch')));
assert.ok(checkMethodSource('tbl-listening',{...source,questions:[...source.questions.slice(0,4),{text:'Question 5',answers:[]}]}).length>0);
assert.ok(checkMethodSource('tbl-listening',{...source,questions:source.questions.map((q,i)=>i===0?{...q,sourceRef:null}:q)}).some(s=>s.includes('source reference')));
assert.ok(checkMethodSource('tbl-listening',{...source,audioSrc:''}).some(s=>s.includes('audioSrc')));
const item={text:'Original text for student A'};
const splitSource={...source,sections:[item,{text:'Original text for student B'}]};
const splitMapped=mapMethodToStates('information-gap-listening',splitSource);
assert.equal(splitMapped.ok,true);
assert.ok(!JSON.stringify(splitMapped.states).includes('Original text for student A'));
assert.ok(!JSON.stringify(splitMapped.states).includes('Original text for student B'));
assert.ok(splitMapped.states.some(s=>s.privateSourceRequired));
assert.ok(checkMethodSource('information-gap-listening',source).some(x=>x.includes('sections')));
assert.ok(checkMethodSource('listening-sequence',{...source,events:[]}).some(x=>x.includes('events')));
assert.ok(checkMethodSource('dictogloss-listening',source).some(x=>x.includes('transcript')));
const dictoglossMapped=mapMethodToStates('dictogloss-listening',{...source,transcript:'Verified original audio transcript'});
assert.equal(dictoglossMapped.ok,true);
assert.ok(!JSON.stringify(dictoglossMapped.states).includes('Verified original audio transcript'));
assert.equal(mapMethodToStates('reciprocal-reading',{passage:'Original reading text',questions:source.questions}).ok,true);
assert.ok(checkMethodSource('reciprocal-reading',{passage:'Original text',questions:source.questions.map(q=>({...q,why:''}))}).some(x=>x.includes('Why')));
assert.equal(mapMethodToStates('grammar-ttt',{grammarTarget:'Second conditional',examples:'Original examples',questions:source.questions}).ok,true);
assert.equal(mapMethodToStates('vocabulary-hot-seat',{items:[{text:'Tornado'}],questions:source.questions}).ok,true);
assert.equal(mapMethodToStates('warmup-picture-quiz',{photoSrc:'/media/nature.webp',targetWord:'tornado'}).ok,true);
console.log('29 method combo variants and source-fidelity tests passed');
