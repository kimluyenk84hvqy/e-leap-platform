import assert from 'node:assert/strict';
import {makeCertifiedTemplate,validateCertifiedTemplate,applyCertifiedTemplate,changeCertifiedVariant} from '../assets/js/authoring/certified-templates.js';
import {evaluateCertifiedGates,certifiedGroupStatus} from '../assets/js/authoring/certification-gates.js';
const cover=makeCertifiedTemplate('cover');
Object.assign(cover.values,{unit:'Unit 12',topic:'Nature',imageSrc:'/assets/nature.webp',imageAlt:'Forest landscape'});
assert.ok(validateCertifiedTemplate(cover).some(x=>x.includes('not been loaded')));
let sc={templateId:'lesson-cover',certifiedTemplate:cover};
assert.equal(certifiedGroupStatus(sc),'BLOCKED');
cover.mediaCheck={src:cover.values.imageSrc,loaded:true};
assert.deepEqual(validateCertifiedTemplate(cover),[]);
assert.equal(certifiedGroupStatus(sc),'AWAITING QA','Verified slots must not be mislabeled as fully approved');
assert.ok(evaluateCertifiedGates(sc).some(g=>g.id==='projection'&&g.status==='pending'));
assert.equal(certifiedGroupStatus({certifiedTemplate:changeCertifiedVariant(cover,'split-editorial')}),'AWAITING QA');
const converted=applyCertifiedTemplate({blocks:[{type:'text',content:{text:'Original Activity 1'}}]},cover).screen;
assert.ok(validateCertifiedTemplate(converted.certifiedTemplate).some(x=>x.includes('source needs review')));
converted.certifiedTemplate.sourceReview={required:true,approved:true,contentSignature:JSON.stringify(converted.certifiedTemplate.values)};
assert.deepEqual(validateCertifiedTemplate(converted.certifiedTemplate),[]);
converted.certifiedTemplate.values.topic='Changed after approval';
assert.ok(validateCertifiedTemplate(converted.certifiedTemplate).some(x=>x.includes('source needs review')));
console.log('Certified QA gates: fail-closed media, source review, variant preservation and pending visual acceptance PASS');
