import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createLesson,duplicateLesson,ensureLessonSchema} from '../assets/js/authoring/lesson-model.js';
import {ELeapAuthoringSaveService} from '../assets/js/authoring-save-service.js';
import {COURSE_PROFILES,ADVANCED_SKILL_PATHS,courseProfileById,courseIsSelectable,createCourseDraft,normaliseCourseIdentity,validateCourseIdentity} from '../assets/js/authoring/course-profile-registry.js';
const ids=COURSE_PROFILES.map(p=>p.id);
assert.equal(new Set(ids).size,ids.length,'Stable course IDs must be unique');
assert.deepEqual(COURSE_PROFILES.filter(x=>x.availability==='planned').map(x=>x.label),
 ['English for Medical Purposes','English for Pharmaceutical Purposes']);
assert.equal(courseIsSelectable('esp-medicine'),false);
assert.equal(courseIsSelectable('esp-pharmacy'),false);
assert.throws(()=>createCourseDraft('esp-pharmacy',createLesson));
assert.throws(()=>createCourseDraft('not-a-book',createLesson));
for(const id of ['objective-pet-b1','objective-first-b2','life','advanced-skills']){
 const prior=createLesson();prior.title='Original work';prior.screens[0].title='Keep this slide';prior.screens.push({id:'old-slide',stage:'Reading',title:'Do not overwrite',blocks:[]});
 const savedPrior=JSON.stringify(prior);
 const created=createCourseDraft(id,createLesson);
 assert.equal(JSON.stringify(prior),savedPrior,'Switching must not mutate previous work');
 assert.notEqual(created.id,prior.id);
 assert.equal(created.courseProfileId,id);
 assert.equal(created.courseLabel,courseProfileById(id).label);
 assert.equal(created.lessonNumber,'');
 assert.equal(created.screens.length,1,'No former course slides may be copied into a new course');
 assert.equal(created.screens[0].blocks.find(x=>x.content?.role==='eyebrow')?.content.text,'New lesson');
 assert.deepEqual(ensureLessonSchema(JSON.parse(JSON.stringify(created))).courseProfileId,id);
 assert.equal(duplicateLesson(created).courseProfileId,id);
}
const legacy=createLesson();delete legacy.courseProfileId;
assert.equal(normaliseCourseIdentity(legacy).courseProfileId,'objective-first-b2');
const unknown=createLesson();unknown.courseLabel='Unrecognized Course';delete unknown.courseProfileId;
assert.equal(normaliseCourseIdentity(unknown).courseProfileId,undefined);
assert.ok(validateCourseIdentity(unknown).length);
const wrong=createCourseDraft('life',createLesson);wrong.courseLabel='Objective PET B1';
assert.ok(validateCourseIdentity(wrong).some(x=>x.includes('disagree')));
const advanced=createCourseDraft('advanced-skills',createLesson);
assert.ok(validateCourseIdentity(advanced).some(x=>x.includes('Advanced Skills branch')));
assert.deepEqual(ADVANCED_SKILL_PATHS.map(x=>x.id),['adv-listening','adv-speaking','adv-reading','adv-writing']);
advanced.advancedSkillId='adv-writing';advanced.courseLibraryShellId='adv-writing';
assert.deepEqual(validateCourseIdentity(advanced),[]);
advanced.courseLibraryShellId='adv-reading';
assert.ok(validateCourseIdentity(advanced).some(x=>x.includes('destination')));
const broken=createCourseDraft('objective-pet-b1',createLesson);
assert.ok(validateCourseIdentity(broken).some(x=>x.includes('verified Platform shell')));
const mem=new Map();globalThis.localStorage={getItem:key=>mem.get(key)||null,setItem:(key,value)=>mem.set(key,String(value))};
const saver=new ELeapAuthoringSaveService();
const draft=createCourseDraft('advanced-skills',createLesson);
draft.advancedSkillId='adv-speaking';draft.courseLibraryShellId='adv-speaking';
saver.saveLocal(draft);
assert.equal(saver.loadLocal(draft.id).lesson.courseProfileId,'advanced-skills');
assert.equal(saver.loadLocal(draft.id).lesson.advancedSkillId,'adv-speaking');
const studio=readFileSync(new URL('../assets/js/authoring-studio.js',import.meta.url),'utf8');
assert.match(studio,/snapshotDraft\(\)/);
assert.match(studio,/readDraftIndex\(\)/);
assert.match(studio,/data-open-draft/);
assert.match(studio,/data-skill-path/);
assert.match(studio,/createCourseDraft\(id,modelCreateLesson\)/);
assert.match(studio,/if\(path==='lesson.title'\)lesson.title=value;else if\(path==='lesson.courseLabel'\)return/);
assert.doesNotMatch(studio,/lesson\.courseLabel=profile\.label/);
console.log('Course authoring contract: separate drafts, stable IDs, planned-course rejection, Advanced Skills branch, legacy, save/reopen checks PASS.');
