import assert from 'node:assert/strict';
import {canonicalAudioName,bindTrackReferences,courseDestination,createNativeLessonRequest} from '../assets/js/authoring/native-authoring-request.js';
assert.equal(canonicalAudioName('026 Track 026.mp3','life'),'life--track-026.mp3');
assert.throws(()=>canonicalAudioName('026 Track 027.mp3','life'));
const uuid='01234567-89ab-4def-8123-456789abcdef';
const pkg={courseProfileId:'life',screens:[{blocks:[{type:'audio',content:{track:26}}]}]};
const file={asset_id:uuid,original_name:'life--track-026.mp3',content_type:'audio/mpeg',status:'active'};
assert.equal(bindTrackReferences(pkg,[file]).screens[0].blocks[0].content.assetId,uuid);
assert.equal(pkg.screens[0].blocks[0].content.assetId,undefined);
assert.throws(()=>bindTrackReferences(pkg,[]));
assert.throws(()=>bindTrackReferences(pkg,[file,file]));
assert.throws(()=>bindTrackReferences(pkg,[{...file,original_name:'objective-first-b2--track-026.mp3'}]));
assert.equal(courseDestination('life','U4.1').shellId,'life-intermediate-u04-l01');
assert.equal(courseDestination('objective-first-b2','U4.2').shellId,'objective-first-b2-u04-l02');
assert.throws(()=>courseDestination('objective-first-b2','U4.3'));
const draft={id:'lesson-test',status:'draft',courseProfileId:'life',lessonNumber:'U4.1',screens:[{title:'PDF page 47',stage:'Imported source',blocks:[{type:'text',content:{text:'Source test'}}]},{title:'PDF page 47',stage:'Imported source',blocks:[{type:'text',content:{text:'Duplicate'}}]}]};
assert.equal(createNativeLessonRequest(draft,{brief:'180 minutes'}).sourcePages.length,0);
assert.equal(createNativeLessonRequest(draft,{brief:'180 minutes',includeSource:true}).sourcePages.length,1);
console.log('native authoring request and track mapping: PASS');
